def _session_cookie(username: str, role: UserRole) -> str:
    response = Response()
    web_auth.get_session_manager().create_session(response, username, role.value)
    cookie: SimpleCookie = SimpleCookie()
    cookie.load(response.headers["set-cookie"])
    return cookie[web_auth.SESSION_COOKIE_NAME].value


def _get_page(client: TestClient, cookie: str):  # type: ignore[no-untyped-def]
    client.cookies.clear()
    client.cookies.set(web_auth.SESSION_COOKIE_NAME, cookie)
    try:
        return client.get(SSH_KEYS_PAGE)
    finally:
        client.cookies.clear()


def test_web_page_without_elevation_sends_admin_to_elevate(
    client, accounts, esm, totp, key_name
) -> None:
    admin = _admin(accounts, totp)
    cookie = _session_cookie(admin, UserRole.ADMIN)
    with enforcement(True):
        response = _get_page(client, cookie)

    assert response.status_code == 303, response.text[:300]
    assert response.headers["location"] == "/admin/elevate?next=%2Fadmin%2Fssh-keys"
    assert key_name not in response.text


def test_web_page_with_elevation_lists_keys(
    client, accounts, esm, totp, key_name
) -> None:
    admin = _admin(accounts, totp)
    cookie = _session_cookie(admin, UserRole.ADMIN)
    esm.create(session_key=cookie, username=admin, elevated_from_ip=None, scope="full")
    with enforcement(True):
        response = _get_page(client, cookie)

    assert response.status_code == 200, response.text[:300]
    assert key_name in response.text


def test_web_page_with_another_users_window_is_refused(
    client, accounts, esm, totp, key_name
) -> None:
    admin, other = _admin(accounts, totp), _admin(accounts, totp)
