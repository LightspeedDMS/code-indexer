"""Listing SSH keys requires TOTP elevation on MCP and on the Web page,
matching REST ``GET /api/ssh-keys`` (``require_elevation()``).

Front doors, on the real app (``create_app`` via ``isolated_app``, never
~/.cidx-server):

- MCP: ``POST /mcp`` ``tools/call list_ssh_keys`` with a Bearer JWT (the
  elevation key is the token's jti).
- Web: ``GET /admin/ssh-keys`` with a Web session cookie (the elevation key
  is the session cookie value).

Elevation windows live in a real ``ElevatedSessionManager`` and TOTP
enrolment in a real ``TOTPService``, both on per-test files, installed at
the read points the gates use.  Only the elevation-enforcement switch is
patched (``self_service_elevation_harness.enforcement``).  The SSH key
listed is a real key generated by the real ``SSHKeyManager`` under the
isolated home.
"""

